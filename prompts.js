  // Типы по ритму: плотные (Hero, Карусель) не идут подряд. prevType — последний пост плана.
  function generateRhythmSequence(n, fixed, prevType, rnd){
    fixed = fixed || []; rnd = rnd || Math.random;
    var airTypes = ["MOOD","MACRO","QUOTE","REELS"];
    var seq = [];
    for (var i = 0; i < n; i++){
      if (fixed[i] && PILLARS[fixed[i]]){ seq.push(fixed[i]); continue; }
      var prev = i > 0 ? seq[i - 1] : prevType;
      var prevDense = prev && PILLARS[prev] && PILLARS[prev].density === "dense";
      var nextDense = fixed[i + 1] && PILLARS[fixed[i + 1]] && PILLARS[fixed[i + 1]].density === "dense";
      var type;
      if (!prevDense && !nextDense && rnd() < 0.55) type = rnd() < 0.6 ? "HERO" : "CAROUSEL";
      else {
        var pool = airTypes.filter(function(t){ return t !== prev; });
        // Reels дают основной охват — даём им двойной вес.
        pool = pool.concat(pool.indexOf("REELS") >= 0 ? ["REELS"] : []);
        type = pool[Math.floor(rnd() * pool.length)];
      }
      seq.push(type);
    }
    return seq;
  }

  // Рубрики по долям: каждый следующий пост получает самую «недобранную» рубрику.
  function assignRubrics(n, rubrics, existing){
    rubrics = (rubrics && rubrics.length ? rubrics : DEFAULT_RUBRICS).filter(function(r){ return r.name; });
    var counts = {}, total = 0;
    rubrics.forEach(function(r){ counts[r.name] = 0; });
    (existing || []).forEach(function(name){ if (name in counts){ counts[name]++; total++; } });
    var sumShare = rubrics.reduce(function(a, r){ return a + (Number(r.share) || 0); }, 0) || 1;
    var out = [];
    for (var i = 0; i < n; i++){
      total++;
      var best = null, bestGap = -Infinity;
      rubrics.forEach(function(r){
        var gap = (Number(r.share) || 0) / sumShare * total - counts[r.name];
        if (gap > bestGap){ bestGap = gap; best = r; }
      });
      counts[best.name]++;
      out.push(best);
    }
    return out;
  }

  // Подбор типа под рубрику с учётом ритма.
  function typeForRubric(rubricName, prevType, rnd){
    rnd = rnd || Math.random;
    var pool = (RUBRIC_TYPES[rubricName] || TYPE_KEYS).slice();
    var prevDense = prevType && PILLARS[prevType] && PILLARS[prevType].density === "dense";
    if (prevDense) pool = pool.filter(function(t){ return PILLARS[t].density === "air"; });
    pool = pool.filter(function(t){ return t !== prevType; });
    if (!pool.length) pool = ["MOOD","MACRO","REELS"].filter(function(t){ return t !== prevType; });
    return pool[Math.floor(rnd() * pool.length)];
  }

