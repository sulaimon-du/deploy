  function parseSceneLine(text){
    text = str(text).trim();
    var m = text.match(/^\s*\**\s*СЦЕНА\s*:\s*([^\n]*)\n+/i);
    if (!m) return {scene: null, prompt: text};
    var parts = m[1].replace(/\*+/g, "").split("|").map(function(x){ x = x.trim(); return x === "—" || x === "-" ? "" : x; });
    return {
      scene: {location: parts[0] || "", light: parts[1] || "", angle: parts[2] || "", props: parts[3] || "", composition: parts[4] || ""},
      prompt: text.slice(m[0].length).trim()
    };
  }

