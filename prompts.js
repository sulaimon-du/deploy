  function checkRepeat(pillarType, scene, prevScenes){
    if (!scene) return null;
    var prev = (prevScenes || []).filter(function(p){ return p && p.pillarType === pillarType; })[0];
    if (!prev) return null;
    var m = [];
    if (pillarType === "HERO" && scene.composition && prev.composition === scene.composition) m.push("приём «" + scene.composition + "»");
    if (scene.location && prev.location === scene.location) m.push("локация «" + scene.location + "»");
    if (scene.angle && prev.angle === scene.angle) m.push("ракурс «" + scene.angle + "»");
    if (!m.length) return null;
    return "Повторяются как в прошлый раз того же типа: " + m.join(", ") + ". Выбери другой вариант.";
  }

